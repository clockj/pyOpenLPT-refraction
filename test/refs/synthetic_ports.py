"""Synthetic calibration data through flat, cylindrical and spherical ports.

Observations are generated by projecting known 3-D points through a correctly
configured C++ camera model, so the ground truth *is* the forward model the
calibrator will invert.  That keeps the two concerns apart: `test_refract_*` files
check that the forward model is right, and calibration tests built on this file
check only that the optimiser recovers the parameters it was given.

Two observation kinds, matching the two calibration workflows:

  * **3D-2D pairs** - known world points with their image coordinates, as a
    machined target or a traversed grid would give.
  * **wand** - pairs of points a fixed distance apart at unknown positions, as a
    waved dumbbell gives.  The 3-D positions are withheld from the calibrator;
    only the separation is known.

Conventions follow the rest of the repository.  For a plate, `pt` lies on the
interface *closest* to the camera and `normal` points away from the camera into
the object medium, which is what `update_cpp_camera_state` expects before it
shifts to the farthest interface.  For a curved port, `refract` is ordered with
the pinhole's medium first, as `doc/refract_curved.tex` numbers them.
"""
from __future__ import annotations

from dataclasses import dataclass, field, replace
from typing import Any, Dict, List, Optional, Sequence, Tuple

import cv2
import numpy as np

try:
    import pyopenlpt as lpt
except ImportError:  # pragma: no cover - the caller skips in that case
    lpt = None


# --------------------------------------------------------------------- specs
@dataclass
class CameraSpec:
    """A pinhole camera: world -> camera is x_cam = R(rvec) X + tvec."""

    rvec: np.ndarray
    tvec: np.ndarray
    f: float = 4000.0
    cx: float = 640.0
    cy: float = 512.0
    width: int = 1280
    height: int = 1024
    k1: float = 0.0
    k2: float = 0.0

    def center(self) -> np.ndarray:
        """Camera centre in world coordinates."""
        rmtx = cv2.Rodrigues(np.asarray(self.rvec, float).reshape(3, 1))[0]
        return -rmtx.T @ np.asarray(self.tvec, float)

    def as_vector(self) -> np.ndarray:
        """The 11-vector layout RefractionPlateCalibrator uses internally."""
        return np.array(
            [*np.asarray(self.rvec, float), *np.asarray(self.tvec, float), self.f,
             self.cx, self.cy, self.k1, self.k2],
            dtype=np.float64,
        )


@dataclass
class PlatePort:
    """A flat window: air | glass slab of `thickness` | object medium."""

    pt: np.ndarray = field(default_factory=lambda: np.zeros(3))
    normal: np.ndarray = field(default_factory=lambda: np.array([0.0, 0.0, -1.0]))
    thickness: float = 10.0
    n_air: float = 1.0
    n_window: float = 1.49
    n_object: float = 1.33


@dataclass
class CurvedPort:
    """A cylindrical or spherical port, indices ordered pinhole-medium first."""

    kind: str  # "cylinder" or "sphere"
    center: np.ndarray = field(default_factory=lambda: np.zeros(3))
    axis: np.ndarray = field(default_factory=lambda: np.array([0.0, 0.0, 1.0]))
    refract: Sequence[float] = (1.0, 1.49, 1.33)
    radii: Sequence[float] = (100.0, 94.0)

    def inner_radius(self) -> float:
        return float(self.radii[-1])


# ------------------------------------------------------------------ cameras
def look_at(center, target, up=(0.0, 0.0, 1.0), **kwargs) -> CameraSpec:
    """A camera at `center` pointing at `target`, with image x right and y down."""
    center = np.asarray(center, float)
    target = np.asarray(target, float)
    z_cam = target - center
    z_cam /= np.linalg.norm(z_cam)
    up = np.asarray(up, float)
    if abs(float(np.dot(up, z_cam))) > 0.95:  # degenerate: pick another up
        up = np.array([0.0, 1.0, 0.0])
    x_cam = np.cross(up, z_cam)
    x_cam /= np.linalg.norm(x_cam)
    y_cam = np.cross(z_cam, x_cam)
    rmtx = np.vstack([x_cam, y_cam, z_cam])
    rvec = cv2.Rodrigues(rmtx)[0].ravel()
    return CameraSpec(rvec=rvec, tvec=-rmtx @ center, **kwargs)


def ring_of_cameras(n_cams, radius, height, target=(0.0, 0.0, 0.0), start_deg=0.0,
                    span_deg=360.0, **kwargs) -> List[CameraSpec]:
    """`n_cams` cameras on a circle of `radius` at `height`, all looking at `target`."""
    out = []
    for i in range(n_cams):
        ang = np.radians(start_deg + span_deg * i / max(n_cams, 1))
        out.append(
            look_at([radius * np.cos(ang), radius * np.sin(ang), height], target, **kwargs)
        )
    return out


def perturb(spec: CameraSpec, rot_rad: float, trans: float, rng) -> CameraSpec:
    """Knock a camera off its true pose, as a bootstrap would leave it.

    The rotation is applied as a proper SO(3) increment rather than by adding to
    the Rodrigues vector, so the requested angle is the angle actually applied.
    """
    axis = rng.normal(size=3)
    axis /= np.linalg.norm(axis)
    d_rmtx = cv2.Rodrigues((axis * rot_rad).reshape(3, 1))[0]
    rmtx = cv2.Rodrigues(np.asarray(spec.rvec, float).reshape(3, 1))[0]
    new_rmtx = d_rmtx @ rmtx
    new_center = spec.center() + rng.normal(size=3) * trans
    return replace(
        spec,
        rvec=cv2.Rodrigues(new_rmtx)[0].ravel(),
        tvec=-new_rmtx @ new_center,
    )


# ------------------------------------------------------- C++ model builders
def build_plate_camera(spec: CameraSpec, port: PlatePort):
    """A PINPLATE camera. `port.pt` is the closest interface; C++ wants the farthest."""
    cam = lpt.Camera()
    normal = np.asarray(port.normal, float)
    normal = normal / np.linalg.norm(normal)
    p_far = np.asarray(port.pt, float) + normal * port.thickness
    cam.setPinplateImageSize(int(spec.height), int(spec.width))
    cam.setPinplateIntrinsics(spec.f, spec.f, spec.cx, spec.cy,
                              [spec.k1, spec.k2, 0.0, 0.0, 0.0])
    cam.setPinplateExtrinsics(lpt.Pt3D(*np.asarray(spec.rvec, float)),
                              lpt.Pt3D(*np.asarray(spec.tvec, float)))
    cam.setPinplateRefraction(
        lpt.Pt3D(*p_far), lpt.Pt3D(*normal),
        [port.n_object, port.n_window, port.n_air], [port.thickness],
        1e-9, 1000, 0.1,
    )
    cam.commitPinplateUpdate(True, 255.0)
    return cam


def build_curved_camera(spec: CameraSpec, port: CurvedPort):
    """A PINCYL or PINSPH camera."""
    cam = (
        lpt.RefractionSphereCameraModel()
        if port.kind == "sphere"
        else lpt.RefractionCylinderCameraModel()
    )
    cam.setImageSize(int(spec.height), int(spec.width))
    cam.setIntrinsics(spec.f, spec.f, spec.cx, spec.cy,
                      [spec.k1, spec.k2, 0.0, 0.0, 0.0])
    cam.setExtrinsics(lpt.Pt3D(*np.asarray(spec.rvec, float)),
                      lpt.Pt3D(*np.asarray(spec.tvec, float)))
    cam.setRefraction(lpt.Pt3D(*np.asarray(port.center, float)),
                      lpt.Pt3D(*np.asarray(port.axis, float)),
                      list(port.refract), list(port.radii))
    cam.setSolverOptions(1e-10, 100)
    cam.commitUpdate()
    return cam


def build_camera(spec: CameraSpec, port):
    return (
        build_plate_camera(spec, port)
        if isinstance(port, PlatePort)
        else build_curved_camera(spec, port)
    )


# --------------------------------------------------------------- projection
def project_points(cam, points: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
    """Project an (N,3) array. Returns (uv (N,2), valid mask (N,)).

    A point is invalid when the refraction solve fails or the image falls outside
    the sensor, which is what a real detector would also miss.
    """
    pts = [lpt.Pt3D(float(p[0]), float(p[1]), float(p[2])) for p in points]
    results = cam.projectBatchStatus(pts, False)
    uv = np.full((len(points), 2), np.nan)
    valid = np.zeros(len(points), dtype=bool)
    n_row, n_col = cam.getNRow(), cam.getNCol()
    for i, rr in enumerate(results):
        ok, pt, _ = rr
        if not ok:
            continue
        u, v = float(pt[0]), float(pt[1])
        if not (np.isfinite(u) and np.isfinite(v)):
            continue
        if not (0.0 <= u < n_col and 0.0 <= v < n_row):
            continue
        uv[i] = (u, v)
        valid[i] = True
    return uv, valid


# ------------------------------------------------------------- observations
def port_radius(port: CurvedPort, points: np.ndarray) -> np.ndarray:
    """Distance of each point from the sphere's centre, or from the cylinder's axis."""
    pts = np.atleast_2d(np.asarray(points, float))
    rel = pts - np.asarray(port.center, float)
    if port.kind == "sphere":
        return np.linalg.norm(rel, axis=1)
    axis = np.asarray(port.axis, float)
    axis = axis / np.linalg.norm(axis)
    return np.linalg.norm(rel - np.outer(rel @ axis, axis), axis=1)


def volume_points(n_points, bounds, rng, port=None, margin=0.98) -> np.ndarray:
    """Random points in an axis-aligned box, pulled inside the port where needed."""
    lo, hi = np.asarray(bounds[0], float), np.asarray(bounds[1], float)
    pts = rng.uniform(lo, hi, size=(int(n_points), 3))
    if not isinstance(port, CurvedPort):
        return pts

    c = np.asarray(port.center, float)
    r_in = port.inner_radius() * margin
    r = port_radius(port, pts)
    scale = np.where(r > r_in, r_in / np.maximum(r, 1e-12), 1.0)
    rel = pts - c
    if port.kind == "sphere":
        return c + rel * scale[:, None]
    axis = np.asarray(port.axis, float)
    axis = axis / np.linalg.norm(axis)
    along = np.outer(rel @ axis, axis)
    return c + along + (rel - along) * scale[:, None]


def plane_stack_points(depths: Sequence[float], extent: float, normal=(1.0, 0.0, 0.0),
                       origin=(0.0, 0.0, 0.0), grid: Tuple[int, int] = (7, 7),
                       port=None, margin: float = 0.95, jitter: float = 0.0,
                       rng=None) -> np.ndarray:
    """A planar grid target placed at several depths along `normal`.

    This is how a calibration is actually taken -- a flat target traversed to a
    few stations -- and it is a different conditioning problem from a random
    cloud. Points on a *single* plane are the classic degenerate case: with the
    focal length free, a plane cannot separate focal from depth at all, and even
    with it fixed the pose is poorly conditioned. Each extra station breaks that.

    `depths` are signed offsets from `origin` along `normal`; `extent` is the
    half-width of the square grid in the plane. Points outside the port's
    innermost interface are dropped, as a real target would be.
    """
    normal = np.asarray(normal, float)
    normal = normal / np.linalg.norm(normal)
    trial = np.array([0.0, 0.0, 1.0]) if abs(normal[2]) < 0.9 else np.array([1.0, 0.0, 0.0])
    e1 = trial - np.dot(trial, normal) * normal
    e1 /= np.linalg.norm(e1)
    e2 = np.cross(normal, e1)

    us = np.linspace(-extent, extent, int(grid[0]))
    vs = np.linspace(-extent, extent, int(grid[1]))
    out = []
    for d in depths:
        base = np.asarray(origin, float) + float(d) * normal
        for u in us:
            for v in vs:
                out.append(base + u * e1 + v * e2)
    pts = np.asarray(out, float)
    if jitter > 0.0 and rng is not None:
        pts = pts + rng.normal(scale=jitter, size=pts.shape)
    if isinstance(port, CurvedPort):
        pts = pts[port_radius(port, pts) <= port.inner_radius() * margin]
    return pts


def make_3d2d_observations_all(cams: Dict[int, Any], points: np.ndarray, rng,
                               noise_px: float = 0.0, min_cams: int = 2,
                               single_only: bool = False) -> List[Dict[str, Any]]:
    """Observations carrying **every** image, not just the primary one.

    Through a curved port a point can appear more than once in the same camera,
    and a real detector would record every blob. `make_3d2d_observations` keeps
    only the primary image, which quietly understates the data a curved port
    actually gives.

    Each record holds one camera and one image, so a point seen twice by one
    camera yields two records with the same `X_world`. That is exactly what a
    ray-based residual wants: both rays pass through the same known point, so
    both constraints are consistent and neither needs a correspondence decision.

    `single_only` drops every point that any camera sees more than once, which is
    the conservative alternative -- and biased, since multi-image points sit at
    the edge of the volume (see the census in the report).
    """
    per_point: Dict[int, Dict[int, List[np.ndarray]]] = {}
    for cid, cam in cams.items():
        for i, p in enumerate(points):
            imgs = _image_set(cam, lpt.Pt3D(float(p[0]), float(p[1]), float(p[2])))
            n_row, n_col = cam.getNRow(), cam.getNCol()
            keep = [uv for uv in imgs if 0.0 <= uv[0] < n_col and 0.0 <= uv[1] < n_row]
            if keep:
                per_point.setdefault(i, {})[cid] = [np.asarray(uv, float) for uv in keep]

    out: List[Dict[str, Any]] = []
    for i, by_cam in per_point.items():
        if len(by_cam) < min_cams:
            continue
        if single_only and any(len(v) > 1 for v in by_cam.values()):
            continue
        for cid, uvs in by_cam.items():
            for uv in uvs:
                q = uv + rng.normal(scale=noise_px, size=2) if noise_px > 0 else uv
                out.append({"X_world": np.asarray(points[i], float),
                            "uv_by_cam": {cid: np.asarray(q, float)}})
    return out


def make_3d2d_observations(cams: Dict[int, Any], points: np.ndarray, rng,
                           noise_px: float = 0.0, min_cams: int = 2) -> List[Dict[str, Any]]:
    """Known 3-D points with their images, in RefractionPlateCalibrator's format.

    Only points seen by at least `min_cams` cameras are kept, as a real detection
    pipeline would require for triangulation.
    """
    uv_by_cam, valid_by_cam = {}, {}
    for cid, cam in cams.items():
        uv, valid = project_points(cam, points)
        if noise_px > 0.0:
            uv = uv + rng.normal(scale=noise_px, size=uv.shape)
        uv_by_cam[cid] = uv
        valid_by_cam[cid] = valid

    out = []
    for i in range(len(points)):
        seen = {cid: uv_by_cam[cid][i] for cid in cams if valid_by_cam[cid][i]}
        if len(seen) >= min_cams:
            out.append({
                "X_world": np.asarray(points[i], float),
                "uv_by_cam": {cid: np.asarray(uv, float) for cid, uv in seen.items()},
            })
    return out


def make_wand_observations(cams: Dict[int, Any], n_frames: int, wand_len: float,
                           bounds, rng, port=None, noise_px: float = 0.0,
                           min_cams: int = 2) -> List[Dict[str, Any]]:
    """Wand frames: two endpoints `wand_len` apart, 3-D positions withheld.

    Each frame carries `uv_by_cam` for both endpoints and the known separation.
    `X_true` is included for scoring only; a calibrator must not read it.
    """
    frames = []
    attempts = 0
    while len(frames) < n_frames and attempts < 50 * n_frames:
        attempts += 1
        mid = volume_points(1, bounds, rng, port)[0]
        d = rng.normal(size=3)
        d /= np.linalg.norm(d)
        a, b = mid - 0.5 * wand_len * d, mid + 0.5 * wand_len * d
        endpoints = np.vstack([a, b])
        if isinstance(port, CurvedPort):
            # Both endpoints must sit inside the innermost interface; a wand that
            # pokes through the port is not a physical observation.
            if np.any(port_radius(port, endpoints) > port.inner_radius() * 0.98):
                continue

        seen: Dict[str, Dict[int, np.ndarray]] = {"A": {}, "B": {}}
        for cid, cam in cams.items():
            uv, valid = project_points(cam, endpoints)
            if noise_px > 0.0:
                uv = uv + rng.normal(scale=noise_px, size=uv.shape)
            if valid[0]:
                seen["A"][cid] = uv[0]
            if valid[1]:
                seen["B"][cid] = uv[1]
        if len(seen["A"]) >= min_cams and len(seen["B"]) >= min_cams:
            frames.append({
                "uv_by_cam": seen,
                "length": float(wand_len),
                "X_true": {"A": a, "B": b},
            })
    return frames


# ------------------------------------------------------------------ scoring
def _image_set(cam, pt) -> List[Tuple[float, float]]:
    """Every image of one point, as (u, v) pixels, skipping the spherical ring.

    Only the curved `CameraModel` classes expose `projectAll`; the plate goes
    through `PyCameraHandle`, whose projection is single-valued anyway (parallel
    interfaces admit exactly one ray), so fall back to `project` there rather
    than returning nothing.
    """
    if not hasattr(cam, "projectAll"):
        uv, ok = project_points(cam, np.asarray([[pt[0], pt[1], pt[2]]], float))
        return [(float(uv[0][0]), float(uv[0][1]))] if ok[0] else []
    try:
        rays, _cov = cam.projectAll(pt)
    except Exception:
        return []
    out = []
    for r in rays:
        if r["is_ring"]:
            continue
        u, v = float(r["pt"][0]), float(r["pt"][1])
        if np.isfinite(u) and np.isfinite(v):
            out.append((u, v))
    return out


def heldout_projection_error(cams_fit: Dict[int, Any], cams_true: Dict[int, Any],
                             points: np.ndarray,
                             match_images: bool = True) -> Dict[str, Any]:
    """Pixel error of the fitted cameras on points that were never calibrated on.

    This is the figure of merit a calibration exists to deliver, and it says
    something the fit residual cannot: the residual only reports how well the
    model explains the points it was *given*. A target confined to one depth
    plane can fit that plane almost perfectly and still extrapolate badly
    elsewhere in the volume, and only held-out points reveal it.

    Both cameras project the same point; the error is the distance between the
    two images. No detection noise is added -- the reference is the true camera's
    own projection, so what is measured is model error alone.

    `visibility_mismatch` counts points one camera can see and the other cannot,
    which is a calibration error in its own right (a particle predicted onto a
    sensor it does not actually fall on, or missed entirely).

    Through a curved port a point can have several images, so comparing "the"
    image of each camera is not well defined: both cameras may return the same
    two images in a different order, or one may have gained a near-branch image
    the other lacks. Either way a single-image comparison reports hundreds of
    pixels where the two agree to a tenth of one. With `match_images` each true
    image is matched to its nearest fitted image instead, which measures the
    calibration rather than the choice of representative.
    """
    errs: List[float] = []
    per_cam: Dict[int, List[float]] = {}
    mismatch = 0
    for cid, cam_fit in cams_fit.items():
        if cid not in cams_true:
            continue
        if match_images:
            d_cam = []
            for p in points:
                pt = lpt.Pt3D(float(p[0]), float(p[1]), float(p[2]))
                a = _image_set(cam_fit, pt)
                b = _image_set(cams_true[cid], pt)
                if not a or not b:
                    mismatch += int(bool(a) != bool(b))
                    continue
                if len(a) != len(b):
                    mismatch += abs(len(a) - len(b))
                # each true image against its nearest fitted image
                for q in b:
                    d_cam.append(min(float(np.hypot(q[0] - r[0], q[1] - r[1])) for r in a))
            per_cam[cid] = d_cam
            errs.extend(d_cam)
            continue
        uv_fit, ok_fit = project_points(cam_fit, points)
        uv_true, ok_true = project_points(cams_true[cid], points)
        mismatch += int(np.sum(ok_fit != ok_true))
        both = ok_fit & ok_true
        d = np.linalg.norm(uv_fit[both] - uv_true[both], axis=1)
        per_cam[cid] = d.tolist()
        errs.extend(d.tolist())
    a = np.asarray(errs, float)
    if a.size == 0:
        return {"n": 0, "median": float("nan"), "p95": float("nan"),
                "max": float("nan"), "rms": float("nan"),
                "visibility_mismatch": mismatch, "per_cam": per_cam}
    return {
        "n": int(a.size),
        "median": float(np.median(a)),
        "p95": float(np.percentile(a, 95)),
        "max": float(a.max()),
        "rms": float(np.sqrt(np.mean(a * a))),
        "visibility_mismatch": mismatch,
        "per_cam": per_cam,
    }


def pose_error(est: CameraSpec, truth: CameraSpec) -> Tuple[float, float]:
    """(rotation error in degrees, centre error in the same units as tvec)."""
    r_est = cv2.Rodrigues(np.asarray(est.rvec, float).reshape(3, 1))[0]
    r_true = cv2.Rodrigues(np.asarray(truth.rvec, float).reshape(3, 1))[0]
    cos = (np.trace(r_est @ r_true.T) - 1.0) / 2.0
    ang = float(np.degrees(np.arccos(np.clip(cos, -1.0, 1.0))))
    return ang, float(np.linalg.norm(est.center() - truth.center()))


def reprojection_rmse(cams: Dict[int, Any], observations: List[Dict[str, Any]]) -> float:
    """RMS distance in pixels between predicted and recorded images."""
    sq, n = 0.0, 0
    for obs in observations:
        X = np.asarray(obs["X_world"], float)[None, :]
        for cid, uv in obs["uv_by_cam"].items():
            pred, valid = project_points(cams[cid], X)
            if not valid[0]:
                continue
            d = pred[0] - np.asarray(uv, float)
            sq += float(d @ d)
            n += 1
    return float(np.sqrt(sq / max(n, 1)))
